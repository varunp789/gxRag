from __future__ import annotations

import hashlib
from datetime import datetime, timezone

import httpx

from app.core.config import settings
from app.models.retrieval import AnswerLog, AnswerRequest, AnswerResponse, Citation, GraphResponse, QueryRequest, QueryResponse, RetrievalResult
from app.services.asset_registry import ARTIFACTS, _find_asset, seed_assets
from app.services.governance import enforce_quota, record

QUERY_LOGS: list[dict[str, str]] = []
ANSWER_LOGS: list[AnswerLog] = []
ANSWER_CACHE: dict[str, AnswerResponse] = {}


def _now() -> str:
    return datetime.now(timezone.utc).isoformat()


def _results(request: QueryRequest, workspace_id: str, mode: str) -> QueryResponse:
    seed_assets()
    terms = {term.lower() for term in request.query.split() if term}
    artifacts = [artifact for artifact in ARTIFACTS if artifact.workspace_id == workspace_id]
    if request.asset_id:
        artifacts = [artifact for artifact in artifacts if artifact.asset_id == request.asset_id]
    results: list[RetrievalResult] = []
    for artifact in artifacts:
        haystack = " ".join([artifact.artifact_type, *artifact.metadata.values()]).lower()
        score = sum(term in haystack for term in terms) / max(len(terms), 1)
        citation = Citation(asset_id=artifact.asset_id, artifact_id=artifact.id, label=artifact.artifact_type, provenance=artifact.provenance)
        results.append(RetrievalResult(id=artifact.id, kind=artifact.artifact_type, content=f"{artifact.artifact_type} generated by {artifact.producer_step}", score=score, metadata=artifact.metadata, citation=citation))
    results = sorted(results, key=lambda item: item.score, reverse=True)[:request.limit]
    QUERY_LOGS.append({"workspace_id": workspace_id, "mode": mode, "query": request.query, "created_at": _now(), "result_count": str(len(results))})
    return QueryResponse(mode=mode, query=request.query, results=results, citations=[item.citation for item in results], graph_paths=[], table_refs=[])


def query(request: QueryRequest, workspace_id: str, mode: str) -> QueryResponse:
    enforce_quota(workspace_id, "query")
    record(workspace_id, "query")
    response = _results(request, workspace_id, mode)
    if mode == "graph":
        response.graph_paths = [[result.citation.asset_id, result.id] for result in response.results if "graph" in result.kind]
    if mode == "structured":
        response.table_refs = [result.id for result in response.results if "structured" in result.kind]
    return response


def graph(asset_id: str, workspace_id: str) -> GraphResponse | None:
    seed_assets()
    asset = _find_asset(asset_id)
    if asset is None or asset.workspace_id != workspace_id:
        return None
    text = " ".join(artifact.artifact_type for artifact in ARTIFACTS if artifact.asset_id == asset_id)
    entities = sorted({word for word in text.split("_") if word})
    return GraphResponse(asset_id=asset_id, entities=entities, relations=[(entities[index], entities[index + 1]) for index in range(max(len(entities) - 1, 0))])


def answer(request: AnswerRequest, workspace_id: str, mode: str) -> AnswerResponse:
    retrieved = query(request, workspace_id, mode)
    cache_key = hashlib.sha256(f"{workspace_id}:{mode}:{request.model}:{request.query}".encode()).hexdigest()
    cached = ANSWER_CACHE.get(cache_key)
    if cached:
        return cached.model_copy(update={"cached": True})
    context = "\n".join(result.content for result in retrieved.results)
    prompt = f"Answer only from this retrieval context.\nContext:\n{context}\n\nQuestion: {request.query}"
    if not settings.openai_api_key:
        answer_text = "Hosted answering needs GXRAG_OPENAI_API_KEY. Retrieval evidence is available in the citations."
        output_tokens = 0
    else:
        response = httpx.post("https://api.openai.com/v1/chat/completions", headers={"Authorization": f"Bearer {settings.openai_api_key}"}, json={"model": request.model, "messages": [{"role": "user", "content": prompt}]}, timeout=60)
        response.raise_for_status()
        body = response.json()
        answer_text = body["choices"][0]["message"]["content"]
        output_tokens = body.get("usage", {}).get("completion_tokens", 0)
    result = AnswerResponse(id=f"answer_{cache_key[:12]}", answer=answer_text, model=request.model, cached=False, input_tokens=max(len(prompt.split()), 1), output_tokens=output_tokens, citations=retrieved.citations)
    ANSWER_CACHE[cache_key] = result
    ANSWER_LOGS.append(AnswerLog(**result.model_dump(), workspace_id=workspace_id, mode=mode, created_at=_now()))
    record(workspace_id, "hosted_tokens", result.input_tokens + result.output_tokens)
    return result
